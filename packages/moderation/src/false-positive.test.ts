import { describe, expect, it } from "vitest";
import { PROFANITY_TH, detectProfanity } from "./detectors.js";

/**
 * เทสต์ชุดนี้คือ "ประโยคที่ลูกค้าจริงพิมพ์" ที่ต้องไม่ถูกซ่อนเด็ดขาด
 * การซ่อนคอมเมนต์ลูกค้าผิดคือความเสียหายที่เรามองไม่เห็น — ลูกค้าเงียบแล้วหายไป
 */
describe("คำที่มีคำหยาบเป็นส่วนประกอบ แต่ไม่ใช่คำหยาบ", () => {
  it("เพจขายสัตว์เลี้ยงต้องคุยเรื่องสัตว์ได้", () => {
    for (const t of [
      "รับฝากสัตว์เลี้ยงไหมคะ",
      "อาหารสัตว์ราคาเท่าไหร่",
      "มีสัตวแพทย์ประจำไหมคะ",
      "โรงพยาบาลสัตว์เปิดกี่โมง",
    ]) {
      expect(detectProfanity(t), t).toBeNull();
    }
  });

  it("คำว่ากูเกิล ไม่ใช่คำหยาบ", () => {
    for (const t of ["หาในกูเกิลได้เลยค่ะ", "ค้นกูเกิลแล้วไม่เจอ"]) {
      expect(detectProfanity(t), t).toBeNull();
    }
  });

  it("ประโยคสุภาพทั่วไป", () => {
    for (const t of [
      "สนใจค่ะ ราคาเท่าไหร่",
      "ขอบคุณมากค่ะ",
      "สั่งซื้อยังไงคะ",
      "ของสวยมากเลยค่ะ",
      "รบกวนสอบถามหน่อยครับ",
    ]) {
      expect(detectProfanity(t), t).toBeNull();
    }
  });
});

describe("แก้ false positive แล้วต้องยังจับคำหยาบจริงได้", () => {
  it("คำด่าตรงๆ ยังถูกจับ", () => {
    for (const t of [
      "เหี้ยอะไรวะ",
      "สัสจริง",
      "ไอ้สัตว์",
      "แม่งเอ๊ย",
      "ฉิบหายแล้ว",
    ]) {
      expect(detectProfanity(t), t).not.toBeNull();
    }
  });

  it("หลบด้วยการแทรกช่องว่างยังถูกจับ", () => {
    expect(detectProfanity("เ ห ี ้ ย")).not.toBeNull();
  });

  it("ยกเว้นเฉพาะตำแหน่งที่เป็นคำสุภาพ ไม่ได้ปิดทั้งประโยค", () => {
    // มีทั้งคำสุภาพที่ยกเว้นและคำหยาบจริงในประโยคเดียว
    expect(detectProfanity("รับฝากสัตว์เลี้ยงไหม ไอ้สัตว์")).not.toBeNull();
  });

  it("ไม่มีคำไหนในลิสต์ที่สั้นจนไปชนคำอื่นได้ง่าย", () => {
    for (const w of PROFANITY_TH) {
      expect(w.length, w).toBeGreaterThanOrEqual(3);
    }
  });
});
