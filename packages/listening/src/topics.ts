/** ตัดวลียกเว้นออก แทนที่ด้วยช่องว่างเพื่อไม่ให้คำสองข้างมาต่อกันเป็นคำใหม่ */
function stripExceptions(text: string): string {
  let out = text;
  // ยาวก่อนสั้น — "ขอบพระคุณ" ต้องถูกตัดก่อน "ขอบคุณ"
  for (const phrase of [...TOPIC_EXCEPTIONS].sort((a, b) => b.length - a.length)) {
    out = out.split(phrase.toLowerCase()).join(" ");
  }
  return out;
}

export interface CommentAnalysis {
  /** หัวข้อที่คอมเมนต์นี้แตะ — หนึ่งคอมเมนต์อยู่ได้หลายหัวข้อ */
  topics: TopicKey[];
  isQuestion: boolean;
}

/** อ่านคอมเมนต์หนึ่งอันแล้วบอกว่าพูดเรื่องอะไรและเป็นคำถามไหม */
export function analyzeComment(raw: string | null | undefined): CommentAnalysis {
  if (raw === null || raw === undefined || raw.trim() === "") {
    return { topics: [], isQuestion: false };
  }

  const text = stripExceptions(normalizeForTopics(raw));

  const topics = TOPICS.filter((t) =>
    t.words.some((w) => text.includes(w.toLowerCase())),
  ).map((t) => t.key);

  const isQuestion = QUESTION_MARKERS.some((m) => text.includes(m.toLowerCase()));

  return { topics, isQuestion };
}

export interface TopicTally {
  key: TopicKey;
  labelTh: string;
  count: number;
}

export interface TopicSummary {
  total: number;
  /** เรียงจากมากไปน้อย และ**ตัดหัวข้อที่ไม่มีใครพูดถึงทิ้ง** */
  topics: TopicTally[];
  questions: number;
  /** สัดส่วนคำถามต่อคอมเมนต์ทั้งหมด (0–100) */
  questionPct: number;
  /** คอมเมนต์ที่ไม่เข้าหัวข้อไหนเลย — บอกไว้ให้รู้ว่าตัวจัดหมวดครอบได้แค่ไหน */
  uncategorized: number;
}

/**
 * นับหัวข้อจากคอมเมนต์ทั้งชุด
 *
 * ผลรวมของทุกหัวข้อ**ไม่เท่ากับ**จำนวนคอมเมนต์ทั้งหมด เพราะคอมเมนต์หนึ่งอัน
 * อยู่ได้หลายหัวข้อและส่วนใหญ่ไม่อยู่หัวข้อไหนเลย (คนพิมพ์ "❤️" กันเยอะ)
 * — `uncategorized` มีไว้ให้เห็นตัวเลขนั้นตรงๆ แทนที่จะปล่อยให้คนคิดว่าหายไปไหน
 */
export function tallyTopics(
  comments: readonly (string | null | undefined)[],
): TopicSummary {
  const counts = new Map<TopicKey, number>();
  let questions = 0;
  let uncategorized = 0;

  for (const c of comments) {
    const a = analyzeComment(c);
    if (a.isQuestion) questions += 1;
    if (a.topics.length === 0) uncategorized += 1;
    for (const t of a.topics) counts.set(t, (counts.get(t) ?? 0) + 1);
  }

  const topics = TOPICS.map((t) => ({
    key: t.key,
    labelTh: t.labelTh,
    count: counts.get(t.key) ?? 0,
  }))
    .filter((t) => t.count > 0)
    .sort((a, b) => b.count - a.count);

  return {
    total: comments.length,
    topics,
    questions,
    questionPct: comments.length === 0 ? 0 : (questions / comments.length) * 100,
    uncategorized,
  };
}
