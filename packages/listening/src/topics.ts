const INVISIBLE = /[​-‍⁠﻿­]/g;

/**
 * normalize เบาๆ พอสำหรับงานนี้
 *
 * ไม่ใช้ตัวของ `packages/moderation` เพราะโจทย์คนละอย่าง — ตัวนั้นออกแบบมาสู้กับ
 * คนที่**ตั้งใจหลบ** filter (แทรกจุด สลับเลขเป็นตัวอักษร) ส่วนตรงนี้ไม่มีใคร
 * พยายามหลบการจัดหมวด การ normalize แรงเกินไปจะทำให้คำพังโดยไม่ได้อะไรกลับมา
 */
export function normalizeForTopics(text: string): string {
  return text.replace(INVISIBLE, "").toLowerCase();
}

