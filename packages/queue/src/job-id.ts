/**
 * แปลงคีย์กันซ้ำของโดเมน → jobId ที่ BullMQ ยอมรับ
 *
 * ─── กับดักที่เจอจริงและเป็นเหตุผลทั้งหมดของไฟล์นี้ ───
 *
 * BullMQ ห้าม custom jobId มีเครื่องหมาย `:` (ยกเว้นกรณีที่แยกแล้วได้ 3 ท่อนพอดี
 * ซึ่งเป็นข้อยกเว้นไว้รองรับของเก่า) ถ้าฝ่าฝืนมันจะโยน `Custom Id cannot contain :`
 * ตอน `add()` — คือตอน **รับ webhook** ไม่ใช่ตอนเทสต์
 *
 * แล้วคีย์ของเราเต็มไปด้วย `:` ทั้งนั้น:
 *
 *   `msg:m_1`                              → 2 ท่อน → พัง
 *   `comment:c_1:add`                      → 3 ท่อน → ผ่าน (บังเอิญ!)
 *   `reaction:mid:sender:react`            → 4 ท่อน → พัง
 *   `publish:p1:page1`                     → 3 ท่อน → ผ่าน (บังเอิญ!)
 *   `publish:p1:page1:retry:2`             → 5 ท่อน → พัง
 *
 * ความบังเอิญที่บางแบบผ่านคือส่วนที่อันตรายที่สุด เพราะเทสต์ที่ลองแค่คอมเมนต์
 * จะเขียวหมด แล้วไปพังตอนมีคนกดไลก์หรือตอนโพสต์ต้อง retry
 *
 * ทางออก: แปลง `:` เป็น `-` แล้ว **ต่อท้ายด้วยแฮชของคีย์เดิม** — ที่ต้องมีแฮช
 * เพราะถ้าแทนที่เฉยๆ `a:b` กับ `a-b` จะกลายเป็น jobId เดียวกัน แล้วงานคนละใบ
 * จะถูกมองว่าซ้ำกันแล้วหายไปหนึ่งใบเงียบๆ
 */
import { createHash } from "node:crypto";

/** ยาวพอให้อ่านออกตอนเปิดดูในคิว แต่ไม่ยาวจนคีย์ Redis เทอะทะ */
const READABLE_MAX = 80;
const HASH_LEN = 12;

export function toJobId(key: string): string {
  if (key === "") {
    throw new Error(
      "คีย์ของงานว่าง — งานที่ไม่มีคีย์กันซ้ำจะทำซ้ำได้ไม่จำกัด (กฎข้อ 6) " +
        "ให้เช็คว่าเรียก idempotencyKey() หรือ publishJobKey() มาถูกตัวหรือยัง",
    );
  }

  const hash = createHash("sha256").update(key, "utf8").digest("hex").slice(0, HASH_LEN);

  const readable = key
    .replace(/:/g, "-")
    // อักขระอื่นที่ไม่ใช่ตัวอักษร/ตัวเลข/`-`/`_` แปลงเป็น `_` เพื่อให้อ่านง่ายเวลา
    // เปิดดูใน redis-cli และไม่ต้องลุ้นว่าเครื่องมือไหน escape ไม่เหมือนกัน
    .replace(/[^A-Za-z0-9_-]/g, "_")
    .slice(0, READABLE_MAX);

  return `${readable}-${hash}`;
}
